DEVICES = {
    "nano4": {
        "title": "MIDI Captain Nano 4",
        "rows": [["1", "2"], ["A", "B"]],
        "pins": {"1": "GP1", "2": "GP25", "A": "GP9", "B": "GP10"}
    },
    "mini6": {
        "title": "MIDI Captain Mini 6",
        "rows": [["1", "2", "3"], ["A", "B", "C"]],
        "pins": {"1": "GP1", "2": "GP25", "3": "GP24", "A": "GP9", "B": "GP10", "C": "GP11"}
    },
    "mc10": {
        "title": "MIDI Captain 10",
        "rows": [["1", "2", "3", "4", "Up"], ["A", "B", "C", "D", "Down"]],
        "pins": {
            "1": "GP1", "2": "GP25", "3": "GP24", "4": "GP23", "Up": "GP20",
            "A": "GP9", "B": "GP10", "C": "GP11", "D": "GP18", "Down": "GP19"
        }
    }
}

# Returns the PySwitch switch assignments for a device, in row order. Only the needed device module is imported.
def get_switches(device):
    rows = DEVICES[device]["rows"]

    if device == "nano4":
        from pyswitch.hardware.devices import pa_midicaptain_nano_4 as m
        prefix = "PA_MIDICAPTAIN_NANO_SWITCH_"
    elif device == "mini6":
        from pyswitch.hardware.devices import pa_midicaptain_mini_6 as m
        prefix = "PA_MIDICAPTAIN_MINI_SWITCH_"
    elif device == "mc10":
        from pyswitch.hardware.devices import pa_midicaptain_10 as m
        prefix = "PA_MIDICAPTAIN_10_SWITCH_"
    else:
        raise Exception("Unknown device: " + repr(device))

    ret = []
    for row in rows:
        for key in row:
            ret.append(getattr(m, prefix + key.upper()))
    return ret


# Screen layout (240x240 display of all MIDI Captains), top to bottom:
#
#   top keys      hint (long press, small) at the outer edge, label (short press) towards the center
#   status        profile / state on the left, power on the right
#   tiles         3 information tiles: caption (small) and value (large)
#   message       last action ("flash") or a profile defined text
#   bottom keys   label, then hint at the outer edge
#
# Rectangles are (x, y, w, h, font). Used by setup.py on the device, the desktop renderer (tools/render.py) and the
# web editor (layout.json, generated by mmtool site).
DISPLAY_SIZE = 240
HINT_HEIGHT = 18
LABEL_HEIGHT = 34
KEY_HEIGHT = HINT_HEIGHT + LABEL_HEIGHT
STATUS_HEIGHT = 18
CAPTION_HEIGHT = 16
TILE_VALUE_HEIGHT = 62
TILES = 3

FONT_SMALL = "/fonts/A12.pcf"
FONT_LABEL = "/fonts/H20.pcf"
FONT_LARGE = "/fonts/PTSans-NarrowBold-40.pcf"

def screen_layout(device):
    rows = DEVICES[device]["rows"]

    keys = {}
    for r in range(len(rows)):
        row = rows[r]
        width = DISPLAY_SIZE // len(row)
        label_font = FONT_LABEL if len(row) <= 3 else FONT_SMALL
        for i in range(len(row)):
            x = i * width
            if r == 0:
                hint_y, label_y = 0, HINT_HEIGHT
            else:
                label_y = DISPLAY_SIZE - KEY_HEIGHT
                hint_y = label_y + LABEL_HEIGHT
            keys[row[i]] = {
                "label": (x, label_y, width, LABEL_HEIGHT, label_font),
                "hint": (x, hint_y, width, HINT_HEIGHT, FONT_SMALL),
            }

    status_y = KEY_HEIGHT
    tiles_y = status_y + STATUS_HEIGHT
    message_y = tiles_y + CAPTION_HEIGHT + TILE_VALUE_HEIGHT
    message_h = DISPLAY_SIZE - KEY_HEIGHT - message_y
    tile_w = DISPLAY_SIZE // TILES

    tiles = []
    for i in range(TILES):
        tiles.append({
            "caption": (i * tile_w, tiles_y, tile_w, CAPTION_HEIGHT, FONT_SMALL),
            "value": (i * tile_w, tiles_y + CAPTION_HEIGHT, tile_w, TILE_VALUE_HEIGHT, FONT_LARGE),
        })

    return {
        "keys": keys,
        "status": (0, status_y, DISPLAY_SIZE - tile_w, STATUS_HEIGHT, FONT_SMALL),
        "power": (DISPLAY_SIZE - tile_w, status_y, tile_w, STATUS_HEIGHT, FONT_SMALL),
        "tiles": tiles,
        "message": (0, message_y, DISPLAY_SIZE, message_h, FONT_LABEL),
    }
